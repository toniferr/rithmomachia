export const LANGS = ['es', 'en'];

function detect() {
  try {
    const saved = localStorage.getItem('rithmo.lang');
    if (LANGS.includes(saved)) return saved;
  } catch { /* storage unavailable */ }
  return 'en'; // English by default; Spanish via the ES button or ?lang=es
}

let lang = detect();

export function getLang() {
  return lang;
}

export function setLang(l) {
  lang = LANGS.includes(l) ? l : 'en';
  try { localStorage.setItem('rithmo.lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
}

// t('key') or t('a.b'); {placeholders} are replaced from `vars`.
export function t(key, vars = {}) {
  let v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), STRINGS[lang]);
  if (v == null) v = key;
  if (typeof v !== 'string') return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}
